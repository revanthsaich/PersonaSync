# ---------- Imports ----------
import os
import cv2
import numpy as np
from insightface.app import FaceAnalysis

# ---------- 1. Initialize InsightFace ----------
app = FaceAnalysis(name="buffalo_l")
app.prepare(ctx_id=0)  # GPU (use -1 for CPU)

# ---------- 2. Utility Functions ----------

def read_image(path):
    """Read image and convert to RGB"""
    img = cv2.imread(path)
    return cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

def normalize(v):
    """L2 normalize vector"""
    return v / np.linalg.norm(v)

# ---------- 3. Extract faces + embeddings (FACE-LEVEL) ----------

def extract_faces_and_embeddings(image):
    faces = app.get(image)
    results = []

    for i, face in enumerate(faces):
        if not is_face_good_quality(image, face.bbox):
            print(f"⚠️ Skipping face {i} (low quality)")
            continue

        emb = face.embedding
        emb = emb / np.linalg.norm(emb)

        results.append({
            "face_index": i,
            "embedding": emb,
            "bbox": face.bbox
        })

    return results

# ---------- 4. Main ML Logic (MEMORY-SPACE SAFE) ----------

MATCH_THRESHOLD = 0.45  # IMPORTANT (real-world photos)

def process_image_in_memory_space(image, person_stats):
    """
    image          : RGB image
    person_stats   : {
        person_id: {
            centroid: np.array,
            count: int
        }
    }
    """
    faces = extract_faces_and_embeddings(image)
    results = []

    for face in faces:
        emb = face["embedding"]

        best_person = None
        best_score = -1

        # Try matching existing personas
        for pid, data in person_stats.items():
            score = np.dot(emb, data["centroid"])
            if score > best_score:
                best_score = score
                best_person = pid

        if best_score >= MATCH_THRESHOLD:
            # SAME PERSON → update centroid
            data = person_stats[best_person]
            data["centroid"] = (
                data["centroid"] * data["count"] + emb
            ) / (data["count"] + 1)
            data["count"] += 1
            person_id = best_person
        else:
            # NEW PERSON
            person_id = f"person_{len(person_stats)}"
            person_stats[person_id] = {
                "centroid": emb,
                "count": 1
            }

        results.append({
            "face_index": face["face_index"],
            "person_id": person_id,
            "confidence": round(best_score, 3)
        })

    return results, person_stats

#face quality check
def is_face_good_quality(image, bbox):
    x1, y1, x2, y2 = map(int, bbox)

    h, w, _ = image.shape
    x1, y1 = max(0, x1), max(0, y1)
    x2, y2 = min(w, x2), min(h, y2)

    face = image[y1:y2, x1:x2]
    if face.size == 0:
        return False

    # --- Size check ---
    fh, fw, _ = face.shape
    if fh < 50 or fw < 50:
        return False

    gray = cv2.cvtColor(face, cv2.COLOR_RGB2GRAY)

    # --- Blur check ---
    blur = cv2.Laplacian(gray, cv2.CV_64F).var()
    if blur < 80:          # ⬆️ stricter than before
        return False

    # --- Brightness check (CRITICAL for your images) ---
    brightness = np.mean(gray)
    if brightness < 60:    # ⬆️ MOST IMPORTANT
        return False
    if brightness > 220:
        return False

    # --- Contrast check (new) ---
    contrast = gray.std()
    if contrast < 25:      # silhouettes fail here
        return False

    return True

