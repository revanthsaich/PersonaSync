import matplotlib.pyplot as plt

def visualize_faces(image, results, title=""):
    """
    image   : RGB image
    results : output from process_image_in_memory_space
    """
    faces = app.get(image)

    img_copy = image.copy()

    for face, res in zip(faces, results):
        x1, y1, x2, y2 = map(int, face.bbox)
        person_id = res["person_id"]

        # Draw rectangle
        cv2.rectangle(img_copy, (x1, y1), (x2, y2), (0, 255, 0), 2)

        # Put text
        cv2.putText(
            img_copy,
            person_id,
            (x1, y1 - 10),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.6,
            (255, 0, 0),
            2
        )

    plt.figure(figsize=(6, 6))
    plt.imshow(img_copy)
    plt.title(title)
    plt.axis("off")
    plt.show()

import os
import cv2
import numpy as np
import matplotlib.pyplot as plt
from collections import defaultdict

# ---------- Storage ----------
person_faces = defaultdict(list)

TEST_DIR = "/content/test_images"
person_stats = {}  # ONE memory space

print("\n🚀 Starting ML Test...\n")

# ---------- Process each image ----------
for img_name in sorted(os.listdir(TEST_DIR)):
    img_path = os.path.join(TEST_DIR, img_name)
    image = read_image(img_path)

    print(f"\n📸 Processing: {img_name}")

    results, person_stats = process_image_in_memory_space(
        image,
        person_stats
    )

    for r in results:
        print(
            f"  Face {r['face_index']} → {r['person_id']} "
            f"(confidence={r['confidence']})"
        )

    # --- Extract faces again for visualization ---
    faces = app.get(image)

    # --- Draw boxes + store crops ---
    img_copy = image.copy()

    for face, res in zip(faces, results):
        x1, y1, x2, y2 = map(int, face.bbox)

        # clamp bbox to image size
        h, w, _ = image.shape
        x1, y1 = max(0, x1), max(0, y1)
        x2, y2 = min(w, x2), min(h, y2)

        crop = image[y1:y2, x1:x2]
        person_faces[res["person_id"]].append(crop)

        # draw box
        cv2.rectangle(img_copy, (x1, y1), (x2, y2), (0, 255, 0), 2)
        cv2.putText(
            img_copy,
            res["person_id"],
            (x1, y1 - 10),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.6,
            (255, 0, 0),
            2
        )

    # --- Show annotated image ---
    plt.figure(figsize=(6, 6))
    plt.imshow(img_copy)
    plt.title(img_name)
    plt.axis("off")
    plt.show()

